const dictionaries: Record<Lang, Record<string, string>> = { en, fr };

function initialLang(): Lang {
  if (typeof localStorage !== 'undefined') {
    const saved = localStorage.getItem('fana.lang');
    if (saved === 'en' || saved === 'fr') return saved;
  }
  if (typeof navigator !== 'undefined' && navigator.language.toLowerCase().startsWith('fr')) {
    return 'fr';
  }
  return 'en';
}

export const lang = writable<Lang>(initialLang());

if (typeof document !== 'undefined') {
  lang.subscribe((value) => {
    document.documentElement.lang = value;
    try {
      localStorage.setItem('fana.lang', value);
    } catch {
      // storage can be unavailable in private mode
    }
  });
}

export function setLang(value: Lang) {
  lang.set(value);
}

export function toggleLang() {
  lang.set(get(lang) === 'en' ? 'fr' : 'en');
}

export type Translate = (key: string, params?: Record<string, string | number>) => string;

export const tr = derived(lang, ($lang): Translate => {
  return (key, params) => {
    let text = dictionaries[$lang][key] ?? dictionaries.en[key] ?? key;
    if (params) {
      for (const [name, value] of Object.entries(params)) {
        text = text.replaceAll(`{${name}}`, String(value));
      }
    }
    return text;
  };
});

export function errorText(translate: Translate, code: string): string {
  const key = `error.${code}`;
  const value = translate(key);
  return value === key ? translate('error.generic') : value;
}

export function noticeText(translate: Translate, code: string, params: Record<string, string>): string {
  const value = translate(code, params);
  return value === code ? '' : value;
}
